#!/usr/bin/env bash
# Usage: gen-index.sh <workspace-root>
# Writes <workspace-root>/REPO_INDEX.md: one line per source file with its top-level
# Python classes/functions and TypeScript exports. Agents grep it instead of exploring.
set -e
ROOT="$(cd "${1:-.}" && pwd)"
OUT="$ROOT/REPO_INDEX.md"
SKIP='/(node_modules|dist|build|coverage|\.venv|venv|__pycache__|\.git|_wt|alembic/versions|migrations)/'
{
  echo "# Symbol index (generated by agents-know scripts/gen-index.sh, do not edit)"
  echo "Grep this file to find where a symbol lives, then open only that file."
  echo
  echo "## Python"
  find "$ROOT" -name '*.py' | grep -Ev "$SKIP" | sort | while read -r f; do
    syms=$(grep -E '^(async def|def|class) [A-Za-z_]' "$f" | sed -E 's/^(async def|def|class) ([A-Za-z0-9_]+).*/\2/' | tr '\n' ' ')
    [ -n "$syms" ] && echo "- ${f#$ROOT/}: $syms"
  done
  echo
  echo "## TypeScript / JavaScript"
  find "$ROOT" \( -name '*.ts' -o -name '*.tsx' -o -name '*.js' -o -name '*.jsx' \) | grep -Ev "$SKIP" | grep -Ev '\.d\.ts$|\.test\.|\.spec\.|__tests__' | sort | while read -r f; do
    syms=$(grep -oE '^export (const|function|interface|type|enum|default function|class|async function) [A-Za-z0-9_]+' "$f" | awk '{print $NF}' | tr '\n' ' ')
    [ -n "$syms" ] && echo "- ${f#$ROOT/}: $syms"
  done
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
